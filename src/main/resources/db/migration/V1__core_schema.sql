CREATE TABLE tenants(
    tenant_id BIGINT GENERATED BY DEFAULT AS IDENTITY ,
    tenant_name VARCHAR(150) NOT NULL ,
    slug VARCHAR(50) NOT NULL ,
    type VARCHAR(20) NOT NULL ,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_At TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_tenants PRIMARY KEY(tenant_id),
    CONSTRAINT uk_tenants_slug UNIQUE(slug),
    CONSTRAINT ck_tenants_type CHECK ( type IN('PLATFORM', 'ORGANISATION') ),
    CONSTRAINT ck_tenants_status CHECK ( status IN ('ACTIVE', 'SUSPENDED') ),
    CONSTRAINT ck_tenant_slug CHECK ( slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);


CREATE UNIQUE INDEX ind_only_one_platform
ON tenants(type)
WHERE type = 'PLATFORM';


CREATE TABLE users(
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY ,
    tenant_id BIGINT NOT NULL ,
    email VARCHAR(150) NOT NULL ,
    password_hash VARCHAR(150) NOT NULL ,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_At TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_At TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_users PRIMARY KEY(user_id),
    CONSTRAINT fk_users_tenants FOREIGN KEY (tenant_id)
    REFERENCES tenants(tenant_id) ON DELETE RESTRICT ,
    CONSTRAINT ck_email_check CHECK ( email = LOWER(email) ),
    CONSTRAINT uk_users_email UNIQUE(email)
);
CREATE UNIQUE INDEX ind_users_tenant_id ON users(tenant_id);

CREATE TABLE roles(
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY ,
    tenant_id BIGINT NOT NULL ,
    role_name VARCHAR(100) NOT NULL ,
    description VARCHAR(255) ,
    is_system BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_At TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_roles PRIMARY KEY(role_id),
    CONSTRAINT fk_roles_tenants FOREIGN KEY(tenant_id)
        REFERENCES tenants(tenant_id)  ON DELETE RESTRICT,
    CONSTRAINT uk_roles_tenants_roles_names UNIQUE (tenant_id, role_name),
    CONSTRAINT ck_roles_name_check CHECK (role_name ~ ^[A-Z0-9]+(_[A-Z0-9]+)*$ )
);

CREATE TABLE permissions(
    permission_id BIGINT GENERATED BY DEFAULT AS IDENTITY ,
    code VARCHAR(100) NOT NULL ,
    scope VARCHAR(20) NOT NULL ,
    description VARCHAR(255),
    active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_permissions PRIMARY KEY (permissions_id),
    CONSTRAINT ck_permissions_scope CHECK ( scope IN('PLATFORM', 'TENANT') ),
    CONSTRAINT uk_permissions_code UNIQUE (code),
    CONSTRAINT ck_permissions_code_format CHECK ( code ~ ^[a-z]+(-[a-z]+)*:[a-z]+(-[a-z]+)*$ )
);

CREATE TABLE user_roles (
    user_id      BIGINT NOT NULL,
    role_id      BIGINT NOT NULL,
    assigned_by  BIGINT,
    assigned_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_user_roles   PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_roles_role  FOREIGN KEY (role_id)
        REFERENCES roles (role_id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_roles_assigned_by FOREIGN KEY (assigned_by)
        REFERENCES users (user_id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX ind_user_role ON user_roles(role_id);

CREATE TABLE role_permissions(
    role_id BIGINT NOT NULL ,
    permission_id BIGINT NOT NULL,
    granted_by BIGINT,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_roles_permissions PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_roles_permissions_user FOREIGN KEY (role_id)
                             REFERENCES roles(role_id) ON DELETE RESTRICT ,
    CONSTRAINT fk_permissions_roles_role FOREIGN KEY (permission_id)
                             REFERENCES permissions(permission_id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_granted FOREIGN KEY (granted_by)
                             REFERENCES users(user_id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX ind_role_permissions ON role_permissions(permission_id);


