CREATE TABLE refresh_tokens(
    refresh_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY ,
    user_id BIGINT NOT NULL ,
    family_id UUID NOT NULL,
    token_hash VARCHAR(64) NOT NULL ,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_refresh_tokens PRIMARY KEY (refresh_token_id),
    CONSTRAINT uk_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id)
                           REFERENCES users(user_id) ON DELETE RESTRICT
);

CREATE INDEX ix_refresh_tokens_user_id ON refresh_tokens(user_id);
CREATE INDEX ix_refresh_tokens_family_id ON refresh_tokens(family_id);

CREATE TABLE audit_logs(
    audit_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY ,
    tenant_id BIGINT NOT NULL ,
    actor_id BIGINT ,
    action VARCHAR(100) NOT NULL ,
    target_type VARCHAR(50) NOT NULL ,
    target_id VARCHAR(100) NOT NULL ,
    details jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_audit_logs PRIMARY KEY (audit_log_id),
    CONSTRAINT fk_audit_logs_tenant FOREIGN KEY (tenant_id)
                       REFERENCES tenants(tenant_id) ON DELETE RESTRICT ,
    CONSTRAINT fk_audit_logs_actor FOREIGN KEY (actor_id)
                       REFERENCES users(user_id) ON DELETE RESTRICT
);

CREATE INDEX ix_audit_logs_tenant_created ON audit_logs(tenant_id, created_at);
