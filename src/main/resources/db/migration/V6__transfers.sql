CREATE TABLE transfers (
    transfer_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id     BIGINT         NOT NULL,
    requested_by  BIGINT         NOT NULL,
    amount        NUMERIC(15, 2) NOT NULL,
    currency      VARCHAR(3)     NOT NULL,
    description   VARCHAR(255),
    status        VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    decided_by    BIGINT,
    decided_at    TIMESTAMPTZ,
    decision_note VARCHAR(255),
    version       BIGINT         NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT pk_transfers PRIMARY KEY (transfer_id),
    CONSTRAINT fk_transfers_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (tenant_id) ON DELETE RESTRICT,
    CONSTRAINT fk_transfers_requested_by FOREIGN KEY (requested_by) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_transfers_decided_by FOREIGN KEY (decided_by) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_transfers_amount CHECK (amount > 0),
    CONSTRAINT ck_transfers_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_transfers_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_transfers_decision CHECK (
        (status = 'PENDING' AND decided_by IS NULL AND decided_at IS NULL)
        OR (status <> 'PENDING' AND decided_by IS NOT NULL AND decided_at IS NOT NULL)
    ),
    CONSTRAINT ck_transfers_not_own CHECK (decided_by IS NULL OR decided_by <> requested_by)
);

CREATE INDEX ix_transfers_tenant_status_created ON transfers (tenant_id, status, created_at);
CREATE INDEX ix_transfers_tenant_requester_created ON transfers (tenant_id, requested_by, created_at);

